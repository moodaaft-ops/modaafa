import { SEND_WINDOW, WEEKLY_REPORT, type SendWindow, type WeeklyReportConfig } from '@/config/email-journeys';

/**
 * Time-zone arithmetic for the lifecycle. Riyadh is UTC+3 all year with no
 * daylight saving, so a fixed offset on plain UTC math is exact and needs no
 * Intl tables (which differ between runtimes). Everything here is pure.
 */
export const RIYADH_OFFSET_MS = 3 * 60 * 60 * 1000;
const HOUR_MS = 60 * 60 * 1000;
const DAY_MS = 24 * HOUR_MS;

/** A Date whose UTC getters read as Riyadh wall-clock time. */
function riyadhWallClock(instant: Date): Date {
  return new Date(instant.getTime() + RIYADH_OFFSET_MS);
}

/** The Riyadh calendar day of an instant, as YYYY-MM-DD. */
export function riyadhDay(instant: Date): string {
  return riyadhWallClock(instant).toISOString().slice(0, 10);
}

/**
 * Saturday 00:00 UTC of the Saudi work week that contains `instant`. This is the
 * week the optimize cron dedupes its weekly report on (`startOfSaudiWeekIso` in
 * app/api/cron/optimize/route.ts: one report per account per week, generated by
 * the first hourly run after Saturday 00:00 UTC), so "generated at or after this
 * instant" means "this week's report". The Sunday 09:00 Riyadh slot and its whole
 * 60 hour window sit inside one such week, and the report is normally written the
 * day BEFORE the slot opens, so the slot start itself is the wrong cut-off.
 */
export function saudiWeekStart(instant: Date): Date {
  const date = new Date(instant.getTime());
  const daysSinceSaturday = (date.getUTCDay() + 1) % 7;
  date.setUTCDate(date.getUTCDate() - daysSinceSaturday);
  date.setUTCHours(0, 0, 0, 0);
  return date;
}

export function riyadhHour(instant: Date): number {
  return riyadhWallClock(instant).getUTCHours();
}

/** 0 = Sunday ... 6 = Saturday, as read on a Riyadh clock. */
export function riyadhWeekday(instant: Date): number {
  return riyadhWallClock(instant).getUTCDay();
}

/** True when the Riyadh hour is in [startHour, endHour): 09:00 inside, 21:59 inside, 22:00 outside. */
export function isInSendWindow(instant: Date, window: SendWindow = SEND_WINDOW): boolean {
  const hour = riyadhHour(instant);
  return hour >= window.startHour && hour < window.endHour;
}

/** ISO 8601 week of a calendar date (the date is already a local date, no zone involved). */
export function isoWeekOf(year: number, month: number, day: number): { isoYear: number; week: number } {
  const target = new Date(Date.UTC(year, month - 1, day));
  const dayNumber = (target.getUTCDay() + 6) % 7; // Monday = 0 ... Sunday = 6
  target.setUTCDate(target.getUTCDate() - dayNumber + 3); // the Thursday of this ISO week
  const isoYear = target.getUTCFullYear();
  const firstThursday = new Date(Date.UTC(isoYear, 0, 4));
  const week =
    1 +
    Math.round(
      ((target.getTime() - firstThursday.getTime()) / DAY_MS - 3 + ((firstThursday.getUTCDay() + 6) % 7)) / 7
    );
  return { isoYear, week };
}

export function weeklyTemplateKey(isoYear: number, week: number): string {
  return `weekly_report_${isoYear}-W${String(week).padStart(2, '0')}`;
}

export type WeeklySlot = {
  /** message_log key, `weekly_report_<ISO year>-W<ww>`. */
  templateKey: string;
  /** The Sunday 09:00 Riyadh this report belongs to. */
  dueAt: Date;
  /** First instant at which the report is no longer sendable. */
  expiresAt: Date;
};

/**
 * The weekly report slot that is open at `now`, or null when the last slot's
 * window (`windowHours` after Sunday 09:00 Riyadh) has closed. The week is the
 * ISO week that contains that Sunday, read on a Riyadh calendar. Because the
 * window is shorter than a week there is never more than one open slot.
 */
export function weeklyReportSlot(now: Date, config: WeeklyReportConfig = WEEKLY_REPORT): WeeklySlot | null {
  const local = riyadhWallClock(now);
  const daysBack = (local.getUTCDay() - config.weekday + 7) % 7;
  let slotLocal = Date.UTC(local.getUTCFullYear(), local.getUTCMonth(), local.getUTCDate() - daysBack, config.hour, 0, 0);
  if (slotLocal > local.getTime()) slotLocal -= 7 * DAY_MS;

  const dueAtMs = slotLocal - RIYADH_OFFSET_MS;
  const expiresAtMs = dueAtMs + config.windowHours * HOUR_MS;
  if (now.getTime() >= expiresAtMs) return null;

  const slotDate = new Date(slotLocal);
  const { isoYear, week } = isoWeekOf(slotDate.getUTCFullYear(), slotDate.getUTCMonth() + 1, slotDate.getUTCDate());
  return {
    templateKey: weeklyTemplateKey(isoYear, week),
    dueAt: new Date(dueAtMs),
    expiresAt: new Date(expiresAtMs),
  };
}
